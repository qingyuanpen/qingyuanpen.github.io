const languageToggle = document.querySelector("[data-language-toggle]");
const translatableElements = document.querySelectorAll("[data-i18n]");
const translatableAriaLabels = document.querySelectorAll("[data-i18n-aria-label]");
const navToggle = document.querySelector("#nav-toggle");

const savedLanguage = localStorage.getItem("site-language");
let currentLanguage = savedLanguage === "en" ? "en" : "zh";

function t(key) {
  return translations[currentLanguage][key] || translations.zh[key] || key;
}

function applyLanguage(language) {
  currentLanguage = language;
  const dictionary = translations[language];

  translatableElements.forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  translatableAriaLabels.forEach((element) => {
    const key = element.dataset.i18nAriaLabel;
    if (dictionary[key]) {
      element.setAttribute("aria-label", dictionary[key]);
    }
  });

  document.documentElement.lang = language === "en" ? "en" : "zh-CN";
  languageToggle.textContent = language === "en" ? "中文/EN" : "EN/中文";
  languageToggle.setAttribute(
    "aria-label",
    language === "en" ? "Switch to Chinese" : "Switch to English"
  );
  localStorage.setItem("site-language", language);
}

languageToggle.addEventListener("click", () => {
  applyLanguage(currentLanguage === "zh" ? "en" : "zh");
});

